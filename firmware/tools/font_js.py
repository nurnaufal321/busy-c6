#!/usr/bin/env python3
"""Turns main/font_data.c into ../../clockfont.js, so the page's preview draws the clock exactly as
the board does. Rerun after tools/gen_font.swift.

Usage: tools/font_js.py
"""
import base64
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = (ROOT / "main" / "font_data.c").read_text()
OUT = ROOT.parent / "clockfont.js"


def font(name: str) -> dict:
    bits = re.search(rf"{name}_bits\[\] = \{{(.*?)\}};", SRC, re.S).group(1)
    data = bytes(int(v) for v in re.findall(r"\d+", bits))
    glyphs = re.search(rf"{name}_glyphs\[\] = \{{(.*?)\n\}};", SRC, re.S).group(1)
    out = {}
    for c, rest in re.findall(r"\{'(\\?.)',\s*([^}]*)\}", glyphs):
        w, h, left, top, advance, offset = (int(v) for v in rest.split(","))
        out[c.replace("\\", "")] = [w, h, left, top, advance, offset]
    return {"glyphs": out, "bits": base64.b64encode(data).decode()}


fonts = {"time": font("font_time"), "date": font("font_date")}
OUT.write_text("// Generated by firmware/tools/font_js.py from firmware/main/font_data.c (Roboto Bold, Apache-2.0). Do not edit.\n"
               f"window.CLOCK_FONTS = {json.dumps(fonts, separators=(',', ':'))};\n")
print(f"{OUT}: {OUT.stat().st_size // 1024} KB, " + ", ".join(f"{k} {len(v['glyphs'])} glyphs" for k, v in fonts.items()))
