#!/usr/bin/env swift
// Renders the clock row's characters to main/font_data.c, as 8-bit coverage, with the Mac's CoreText.
// Usage: tools/gen_font.swift <Roboto-Bold.ttf> > main/font_data.c
//
// Roboto is Apache-2.0; it ships in the Android SDK at platforms/android-28/data/fonts.
import CoreGraphics
import CoreText
import Foundation

let args = CommandLine.arguments
guard args.count == 2, let provider = CGDataProvider(filename: args[1]), let cg = CGFont(provider) else {
    FileHandle.standardError.write("usage: gen_font.swift <font.ttf>\n".data(using: .utf8)!)
    exit(1)
}

let sets: [(name: String, size: CGFloat, chars: String)] = [
    ("font_time", 72, "0123456789:-"),
    ("font_date", 30, "0123456789 ABCDEFGHIJLMNOPRSTUVWY"),
]

print("// Generated by tools/gen_font.swift from Roboto Bold (Apache-2.0). Do not edit.")
print("#include \"font.h\"\n")

for set in sets {
    let font = CTFontCreateWithGraphicsFont(cg, set.size, nil, nil)
    var bytes: [UInt8] = []
    var rows: [String] = []
    for ch in set.chars {
        var unichar = Array(String(ch).utf16)
        var glyph: CGGlyph = 0
        CTFontGetGlyphsForCharacters(font, &unichar, &glyph, 1)
        var advance = CGSize.zero
        CTFontGetAdvancesForGlyphs(font, .horizontal, &glyph, &advance, 1)
        let box = CTFontGetBoundingRectsForGlyphs(font, .horizontal, &glyph, nil, 1).integral
        let w = Int(box.width), h = Int(box.height)
        let start = bytes.count
        if w > 0 && h > 0 {
            var buf = [UInt8](repeating: 0, count: w * h)
            let ctx = CGContext(data: &buf, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                                space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
            ctx.setAllowsAntialiasing(true)
            ctx.setShouldAntialias(true)
            ctx.setFillColor(gray: 1, alpha: 1)
            var pos = CGPoint(x: -box.minX, y: -box.minY)
            CTFontDrawGlyphs(font, &glyph, &pos, 1, ctx)
            bytes += buf
        }
        // left bearing; top = pixels from the top of the glyph up to the baseline
        rows.append("    {'\(ch)', \(w), \(h), \(Int(box.minX)), \(Int(box.maxY)), \(Int(advance.width.rounded())), \(start)},")
    }
    print("static const uint8_t \(set.name)_bits[] = {")
    var i = 0
    while i < bytes.count {
        print("    " + bytes[i..<min(i + 24, bytes.count)].map { String($0) }.joined(separator: ",") + ",")
        i += 24
    }
    print("};\n")
    print("static const glyph_t \(set.name)_glyphs[] = {")
    rows.forEach { print($0) }
    print("};\n")
    print("const font_t \(set.name) = {\(set.name)_glyphs, \(rows.count), \(set.name)_bits};\n")
}
